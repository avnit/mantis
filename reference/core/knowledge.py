"""The knowledge base as text: export to, and import from, `.mantis/knowledge/`.

What the pipeline learns about a codebase -- its findings and their status,
the threat model and architecture it drew, what it has covered, and what it
learned about the code's habits -- lives in the knowledge database, scoped to
runs. That is the right shape for a run and the wrong shape for a repository:
nobody opens the database, nothing survives a fresh checkout, and a reviewer
cannot see a claim change.

This module writes the same knowledge as plain text, one record per line,
deterministically ordered, so it can be committed to the repository under
`.mantis/knowledge/` and read back into a fresh database before the next run.
Checked in, it is versioned, diffable, and reviewed like any other claim about
the system. Read back, it is the memory a run would otherwise rebuild from
nothing.

Trust runs one way. Export scrubs credentials and control characters from
every string. Import treats every byte as untrusted data: schema version
checked, sizes capped, paths validated, strings bounded and stripped, and
nothing is executed or interpolated. A reader that must not trust the working
tree (a pull-request scan) reads the files from the base commit, not from the
checkout; that is the caller's job, this module only parses what it is given.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import sqlite3
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Tuple

SCHEMA_VERSION = 2
# Versions this importer reads. 1 predates per-record model provenance; its
# records import with an unknown model.
READABLE_SCHEMA_VERSIONS = (1, 2)
KNOWLEDGE_DIR = ".mantis/knowledge"

MANIFEST = "manifest.json"
FINDINGS = "findings.jsonl"
LEARNINGS = "learnings.jsonl"
THREAT_MODEL_JSON = "threat_model.json"
THREAT_MODEL_MD = "threat_model.md"
ARCHITECTURE_MD = "architecture.md"
SUMMARY_JSON = "summary.json"
COVERAGE = "coverage.json"
RUNS = "runs.jsonl"
README = "README.md"

# Artifact paths the pipeline's own tools read (tools/research_tools.py); the
# import writes under these so a run sees imported knowledge through the same
# calls it would use for its own.
_ART_THREAT_MODEL = ("threat_model", "workspace/.structured/threat_model.json")
_ART_THREAT_MODEL_MD = ("kb", "workspace/kb/THREAT_MODEL.md")
_ART_ARCHITECTURE = ("kb", "workspace/kb/architecture.md")
_ART_SUMMARY = ("summary", "workspace/.structured/summary.json")

# Fields a finding carries into the export. An allowlist, not the row: the
# embedding is a derived blob, the patch diff is a byte-exact payload that
# belongs in a SARIF or a pull request, and anything added to the table later
# is not exported until someone decides it should be.
FINDING_FIELDS = (
    "lineage_id", "signature", "filepath", "line_numbers", "title", "severity",
    "priority", "cwe", "status", "description", "remediation", "triage_reasoning",
    "rca_summary", "code_paths", "mantis_risk_score", "impact_score",
    "likelihood_score", "patch_status", "run_id", "model", "timestamp",
)
_TEXT_FIELDS = ("title", "description", "remediation", "triage_reasoning", "rca_summary")

# Import bounds. A hostile or merely broken file must cost the run nothing but
# the knowledge it would have carried.
MAX_FILE_BYTES = 32 * 1024 * 1024
MAX_LINE_BYTES = 512 * 1024
MAX_TEXT_CHARS = 20_000
MAX_SHORT_CHARS = 300
MAX_LIST_ITEMS = 500
_IDENT_RE = re.compile(r"^[A-Za-z0-9._:@+-]{1,128}$")
_STATUS_RE = re.compile(r"^[a-z][a-z0-9_]{0,39}$")

README_TEXT = """\
# Mantis knowledge

Generated by Mantis from its knowledge database; tool state, kept in the
repository so it is versioned and reviewable. One record per line, sorted, so
a re-export diffs cleanly.

- `findings.jsonl`: one finding per line with its lineage id and status.
- `runs.jsonl`: which model each run used; findings, learnings and coverage
  entries name their run, and so their model. Knowledge built by more than
  one model keeps who found what and who covered what.
- `threat_model.json` / `.md`, `architecture.md`, `summary.json`: the model's
  current map of the system.
- `coverage.json`: what has been scanned, and at which snapshot.
- `learnings.jsonl`: what the pipeline learned about this codebase.

Regenerate with `scripts/knowledge.py export`; a run reads it back with
`main.py --import-knowledge`. Edits are allowed and are treated as data.
"""


# --- shared -----------------------------------------------------------------------


# Characters that change how text reads without being visible in it:
# bidirectional overrides and isolates, zero-width joiners and spaces, soft
# hyphens, byte-order marks. An export is committed and reviewed as a diff;
# none of these belong in one.
_INVISIBLE_RE = re.compile("[\u200b-\u200f\u202a-\u202e\u2060-\u2064\u2066-\u2069\ufeff\u00ad]")


def _scrub(text: Any, limit: int = MAX_TEXT_CHARS) -> str:
    """Credential- and control-scrubbed text, bounded, with the invisible
    direction- and width-changing characters removed."""
    if text is None:
        return ""
    try:
        from core.llm_gateway import sanitize_egress_text

        out = sanitize_egress_text(str(text))
    except Exception:
        out = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f-\x9f]", "", str(text))
    out = _INVISIBLE_RE.sub("", out)
    return out[:limit]


def _scrub_markdown(text: Any, limit: int = MAX_TEXT_CHARS) -> str:
    """_scrub plus no HTML: a committed `.md` renders on the hosting site, and
    model-written prose must not carry a hidden comment, a collapsed block,
    or a link into it. Angle brackets are encoded, which keeps code and
    prose readable and keeps every tag inert."""
    out = _scrub(text, limit)
    return out.replace("<", "&lt;").replace(">", "&gt;")


def _clean_rel_path(value: Any) -> str:
    """A repository-relative path, or '' if the value is not one.

    Absolute paths, parent references, NULs, and backslash separators are
    refused rather than repaired: a path the exporter would not have written
    is a path the importer must not store.
    """
    s = str(value or "")
    if not s or "\0" in s or "\\" in s or s.startswith("/") or len(s) > 1024:
        return ""
    parts = s.split("/")
    if any(p in ("", ".", "..") for p in parts):
        return ""
    return s


def _relativize(path: str, root: Optional[str]) -> str:
    """`path` relative to `root`, or '' when it is outside (or root is unknown)."""
    if not root:
        return ""
    try:
        rp = os.path.realpath(path)
        rr = os.path.realpath(root)
        if rp == rr:
            return "."
        if os.path.commonpath([rp, rr]) != rr:
            return ""
        return os.path.relpath(rp, rr).replace(os.sep, "/")
    except (ValueError, OSError):
        return ""


def _json_line(obj: Dict[str, Any]) -> str:
    return json.dumps(obj, sort_keys=True, ensure_ascii=False, separators=(",", ":"))


def _connect(db_path: str) -> sqlite3.Connection:
    from core.database import connect

    conn = connect(db_path)
    conn.row_factory = sqlite3.Row
    return conn


def _parse_list(raw: Any, max_items: int = MAX_LIST_ITEMS) -> List[Any]:
    if isinstance(raw, list):
        items = raw
    elif isinstance(raw, str) and raw:
        try:
            items = json.loads(raw)
        except ValueError:
            return []
        if not isinstance(items, list):
            return []
    else:
        return []
    return items[:max_items]


# --- export -----------------------------------------------------------------------


def _run_models(conn: sqlite3.Connection) -> Dict[str, str]:
    """{run_id: model} from the runs table; empty when there is none."""
    try:
        return {str(r[0]): str(r[1] or "") for r in conn.execute("SELECT run_id, model FROM runs").fetchall() if r[0]}
    except sqlite3.Error:
        return {}


def _export_runs(conn: sqlite3.Connection) -> List[Dict[str, Any]]:
    try:
        rows = conn.execute("SELECT run_id, model, started FROM runs ORDER BY started ASC, run_id ASC").fetchall()
    except sqlite3.Error:
        return []
    return [{"run_id": _scrub(r[0], MAX_SHORT_CHARS), "model": _scrub(r[1], MAX_SHORT_CHARS),
             "started": _scrub(r[2], MAX_SHORT_CHARS)} for r in rows if r[0]]


def _export_findings(conn: sqlite3.Connection, repo_root: Optional[str]) -> List[Dict[str, Any]]:
    """Latest row per lineage (or per signature, or per location+title when the
    row predates both), as the export's view of each finding. Each carries
    the model of the run that wrote it, when the database knows it."""
    models = _run_models(conn)
    try:
        rows = conn.execute("SELECT * FROM findings ORDER BY id ASC").fetchall()
    except sqlite3.Error:
        return []
    latest: Dict[Tuple[str, str], sqlite3.Row] = {}
    for row in rows:
        r = dict(row)
        if r.get("lineage_id"):
            key = ("lineage", str(r["lineage_id"]))
        elif r.get("signature"):
            key = ("signature", str(r["signature"]))
        else:
            key = ("loc", f"{r.get('filepath')}|{r.get('title')}|{r.get('line_numbers')}")
        latest[key] = row  # later rows win: ORDER BY id ASC
    out: List[Dict[str, Any]] = []
    for row in latest.values():
        r = dict(row)
        rec: Dict[str, Any] = {}
        for f in FINDING_FIELDS:
            v = models.get(str(r.get("run_id") or ""), "") if f == "model" else r.get(f)
            if f == "filepath":
                v = str(v or "")
                if os.path.isabs(v):
                    v = _relativize(v, repo_root) or v
                v = _scrub(v, 1024)
            elif f in ("line_numbers", "code_paths"):
                v = _parse_list(v)
                if f == "line_numbers":
                    v = [int(x) for x in v if isinstance(x, int) and not isinstance(x, bool) and x > 0]
                else:
                    v = [_scrub(x, 1024) for x in v if isinstance(x, str)]
            elif f in _TEXT_FIELDS:
                v = _scrub(v)
            elif isinstance(v, str):
                v = _scrub(v, MAX_SHORT_CHARS)
            rec[f] = v
        out.append(rec)
    out.sort(key=lambda r: (str(r.get("filepath") or ""), str(r.get("lineage_id") or ""),
                            str(r.get("title") or ""), str(r.get("signature") or "")))
    return out


def _export_learnings(conn: sqlite3.Connection) -> List[Dict[str, Any]]:
    models = _run_models(conn)
    try:
        rows = conn.execute(
            "SELECT run_id, timestamp, category, learning, tags FROM learnings ORDER BY id ASC"
        ).fetchall()
    except sqlite3.Error:
        return []
    seen: Dict[Tuple[str, str], Dict[str, Any]] = {}
    for row in rows:
        r = dict(row)
        cat = _scrub(r.get("category"), MAX_SHORT_CHARS)
        text = _scrub(r.get("learning"))
        if not text:
            continue
        seen[(cat, text)] = {
            "category": cat,
            "learning": text,
            "tags": [_scrub(t, MAX_SHORT_CHARS) for t in _parse_list(r.get("tags")) if isinstance(t, str)],
            "run_id": _scrub(r.get("run_id"), MAX_SHORT_CHARS),
            "model": models.get(str(r.get("run_id") or ""), ""),
            "timestamp": _scrub(r.get("timestamp"), MAX_SHORT_CHARS),
        }
    return sorted(seen.values(), key=lambda x: (x["category"], x["learning"]))


def _latest_artifact(conn: sqlite3.Connection, artifact_type: str = "",
                     filepaths: Iterable[str] = ()) -> Optional[str]:
    clauses, params = [], []
    if artifact_type:
        clauses.append("artifact_type = ?")
        params.append(artifact_type)
    fps = list(filepaths)
    if fps:
        clauses.append("filepath IN (%s)" % ",".join("?" * len(fps)))
        params.extend(fps)
    if not clauses:
        return None
    try:
        row = conn.execute(
            "SELECT content FROM campaign_artifacts WHERE " + " AND ".join(clauses)
            + " ORDER BY id DESC LIMIT 1", params).fetchone()
    except sqlite3.Error:
        return None
    return str(row[0]) if row and row[0] is not None else None


def _export_coverage(conn: sqlite3.Connection, repo_root: Optional[str]) -> Dict[str, Any]:
    """Coverage as repository-relative paths: the ledger's examined areas per
    run, and every target a completed campaign recorded spend for -- per
    model, so a path one model covered is still open for another."""
    from core.memory import COVERAGE_ARTIFACT_TYPE

    models = _run_models(conn)
    runs: List[Dict[str, Any]] = []
    try:
        rows = conn.execute(
            "SELECT content FROM campaign_artifacts WHERE artifact_type LIKE ? ORDER BY id ASC",
            (COVERAGE_ARTIFACT_TYPE + ":%",)).fetchall()
    except sqlite3.Error:
        rows = []
    seen_runs = set()
    for (content,) in rows:
        try:
            parsed = json.loads(content or "{}")
        except ValueError:
            continue
        for entry in (parsed.get("runs") or []) if isinstance(parsed, dict) else []:
            if not isinstance(entry, dict):
                continue
            run_id = _scrub(entry.get("run_id"), MAX_SHORT_CHARS)
            examined = sorted({_relativize(str(p), repo_root) for p in (entry.get("examined") or [])
                               if isinstance(p, str)} - {""})
            key = (run_id, tuple(examined))
            if not examined or key in seen_runs:
                continue
            seen_runs.add(key)
            runs.append({"run_id": run_id,
                         "model": models.get(run_id, ""),
                         "snapshot_id": _scrub(entry.get("snapshot_id"), MAX_SHORT_CHARS),
                         "examined": examined})
    scanned: Dict[str, Dict[str, Any]] = {}
    try:
        spend = conn.execute(
            "SELECT target, scan_mode, run_id, tokens FROM campaign_spend ORDER BY id ASC").fetchall()
    except sqlite3.Error:
        spend = []
    for row in spend:
        r = dict(row)
        rel = _relativize(str(r.get("target") or ""), repo_root)
        if not rel:
            continue
        run_id = _scrub(r.get("run_id"), MAX_SHORT_CHARS)
        model = models.get(run_id, "")
        scanned[(rel, model)] = {"path": rel, "scan_mode": _scrub(r.get("scan_mode"), MAX_SHORT_CHARS),
                                 "last_run_id": run_id, "model": model}
    return {"schema_version": SCHEMA_VERSION, "runs": runs,
            "scanned": [scanned[k] for k in sorted(scanned)]}


def _git_head(repo_root: Optional[str]) -> str:
    """The commit the repository is at, or '' when it is not a git checkout."""
    if not repo_root:
        return ""
    try:
        import subprocess

        out = subprocess.run(["git", "-C", str(repo_root), "rev-parse", "--verify", "--quiet",
                              "--end-of-options", "HEAD"], capture_output=True, text=True, timeout=30)
        sha = out.stdout.strip()
        return sha if out.returncode == 0 and re.fullmatch(r"[0-9a-f]{7,64}", sha) else ""
    except Exception:
        return ""


def read_head(in_dir: str) -> str:
    """The commit a knowledge export says it reflects (manifest `head`), or ''."""
    raw = _read_bounded(Path(in_dir) / MANIFEST, 1 << 20)
    if raw is None:
        return ""
    try:
        manifest = json.loads(raw.decode("utf-8", errors="replace"))
    except ValueError:
        return ""
    head = manifest.get("head") if isinstance(manifest, dict) else None
    return head if isinstance(head, str) and re.fullmatch(r"[0-9a-f]{7,64}", head) else ""


def export_knowledge(db_path: str, out_dir: str, repo_root: Optional[str] = None,
                     head: Optional[str] = None) -> Dict[str, Any]:
    """Writes the knowledge base under `out_dir` as text. Returns counts.

    `repo_root` is the directory finding paths are relative to and the root
    coverage paths are made relative to; anything outside it is left out.
    `head` is the commit the knowledge reflects (defaults to the checkout's
    HEAD); an incremental refresh uses it as the base of its next diff. The
    output is deterministic for a given database and head: the same rows
    produce the same bytes, so a re-export after a run diffs to exactly what
    changed.
    """
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    conn = _connect(db_path)
    try:
        findings = _export_findings(conn, repo_root)
        learnings = _export_learnings(conn)
        tm_json = _latest_artifact(conn, artifact_type=_ART_THREAT_MODEL[0])
        tm_md = _latest_artifact(conn, filepaths=("workspace/kb/THREAT_MODEL.md", "workspace/kb/threat_model.md"))
        arch_md = _latest_artifact(conn, filepaths=(_ART_ARCHITECTURE[1],))
        summary_json = _latest_artifact(conn, artifact_type=_ART_SUMMARY[0])
        coverage = _export_coverage(conn, repo_root)
        runs = _export_runs(conn)
    finally:
        conn.close()

    def write(name: str, text: str) -> None:
        (out / name).write_text(text, encoding="utf-8")

    def pretty_json(raw: Optional[str]) -> Optional[str]:
        if raw is None:
            return None
        try:
            return json.dumps(json.loads(raw), indent=2, sort_keys=True, ensure_ascii=False) + "\n"
        except ValueError:
            return None

    models = sorted({r["model"] for r in runs if r.get("model")})
    counts = {"findings": len(findings), "learnings": len(learnings),
              "threat_model": bool(tm_json or tm_md), "architecture": bool(arch_md),
              "summary": bool(summary_json), "coverage_runs": len(coverage["runs"]),
              "coverage_paths": len(coverage["scanned"]), "runs": len(runs), "models": models}
    write(FINDINGS, "".join(_json_line(f) + "\n" for f in findings))
    write(LEARNINGS, "".join(_json_line(x) + "\n" for x in learnings))
    write(RUNS, "".join(_json_line(r) + "\n" for r in runs))
    for name, text in ((THREAT_MODEL_JSON, pretty_json(_scrub(tm_json, 10**7) if tm_json else None)),
                       (THREAT_MODEL_MD, _scrub_markdown(tm_md, 10**6) if tm_md else None),
                       (ARCHITECTURE_MD, _scrub_markdown(arch_md, 10**6) if arch_md else None),
                       (SUMMARY_JSON, pretty_json(_scrub(summary_json, 10**7) if summary_json else None))):
        if text:
            write(name, text if text.endswith("\n") else text + "\n")
        elif (out / name).exists():
            (out / name).unlink()
    write(COVERAGE, json.dumps(coverage, indent=2, sort_keys=True, ensure_ascii=False) + "\n")
    write(README, README_TEXT)
    digest = hashlib.sha256()
    for name in (FINDINGS, LEARNINGS, THREAT_MODEL_JSON, THREAT_MODEL_MD, ARCHITECTURE_MD, SUMMARY_JSON, COVERAGE, RUNS):
        p = out / name
        if p.exists():
            digest.update(name.encode()); digest.update(p.read_bytes())
    manifest = {"schema_version": SCHEMA_VERSION, "generator": "mantis", "counts": counts,
                "models": models, "content_sha256": digest.hexdigest()}
    head = head if head is not None else _git_head(repo_root)
    if head:
        manifest["head"] = head
        counts["head"] = head
    write(MANIFEST, json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    return counts


# --- import -----------------------------------------------------------------------


class KnowledgeImportError(Exception):
    """The directory is not a knowledge export this version can read."""


def _read_bounded(path: Path, limit: int = MAX_FILE_BYTES) -> Optional[bytes]:
    try:
        st = os.stat(path, follow_symlinks=False)
    except OSError:
        return None
    if not os.path.isfile(path) or os.path.islink(path) or st.st_size > limit:
        return None
    with open(path, "rb") as fh:
        return fh.read(limit + 1)[:limit]


def _iter_jsonl(path: Path) -> Iterable[Dict[str, Any]]:
    raw = _read_bounded(path)
    if raw is None:
        return
    for line in raw.splitlines():
        if not line.strip() or len(line) > MAX_LINE_BYTES:
            continue
        try:
            obj = json.loads(line.decode("utf-8", errors="replace"))
        except ValueError:
            continue
        if isinstance(obj, dict):
            yield obj


def _short(value: Any) -> str:
    return _scrub(value, MAX_SHORT_CHARS) if isinstance(value, (str, int, float)) and not isinstance(value, bool) else ""


def _number(value: Any) -> Optional[float]:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    return float(value) if value == value and abs(value) < 1e12 else None  # no NaN/inf


def _import_findings(conn: sqlite3.Connection, path: Path) -> Tuple[int, int]:
    """Inserts findings the database has not seen: a lineage (or signature)
    already present is left alone, since the database's row is at least as
    current as the export's. Returns (inserted, skipped)."""
    inserted = skipped = 0
    for rec in _iter_jsonl(path):
        filepath = _clean_rel_path(rec.get("filepath"))
        title = _scrub(rec.get("title"), MAX_SHORT_CHARS)
        status = str(rec.get("status") or "").strip().lower()
        if not filepath or not title or not _STATUS_RE.match(status):
            skipped += 1
            continue
        lineage = _short(rec.get("lineage_id"))
        signature = _short(rec.get("signature"))
        if lineage and not _IDENT_RE.match(lineage):
            lineage = ""
        try:
            if lineage and conn.execute("SELECT 1 FROM findings WHERE lineage_id = ? LIMIT 1", (lineage,)).fetchone():
                skipped += 1
                continue
            if signature and conn.execute("SELECT 1 FROM findings WHERE signature = ? LIMIT 1", (signature,)).fetchone():
                skipped += 1
                continue
            lines = [int(x) for x in _parse_list(rec.get("line_numbers"))
                     if isinstance(x, int) and not isinstance(x, bool) and 0 < x < 10**7]
            code_paths = [_clean_rel_path(x) or _scrub(x, MAX_SHORT_CHARS)
                          for x in _parse_list(rec.get("code_paths")) if isinstance(x, str)]
            conn.execute(
                """INSERT OR IGNORE INTO findings
                   (run_id, filepath, title, severity, description, line_numbers, remediation,
                    status, mantis_risk_score, impact_score, likelihood_score, priority,
                    signature, lineage_id, cwe, triage_reasoning, patch_status, rca_summary, code_paths)
                   VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
                (_short(rec.get("run_id")) or "imported", filepath, title,
                 _short(rec.get("severity")), _scrub(rec.get("description")), json.dumps(lines),
                 _scrub(rec.get("remediation")), status, _number(rec.get("mantis_risk_score")),
                 _number(rec.get("impact_score")), _number(rec.get("likelihood_score")),
                 _short(rec.get("priority")), signature or None, lineage or None,
                 _short(rec.get("cwe")), _scrub(rec.get("triage_reasoning")),
                 _short(rec.get("patch_status")), _scrub(rec.get("rca_summary")), json.dumps(code_paths)))
            inserted += 1
        except sqlite3.Error:
            skipped += 1
    return inserted, skipped


def _import_learnings(conn: sqlite3.Connection, path: Path) -> int:
    n = 0
    for rec in _iter_jsonl(path):
        text = _scrub(rec.get("learning"))
        cat = _short(rec.get("category"))
        if not text:
            continue
        run_id = _short(rec.get("run_id")) or "imported"
        try:
            if conn.execute("SELECT 1 FROM learnings WHERE category = ? AND learning = ? LIMIT 1",
                            (cat, text)).fetchone():
                continue
            tags = [_scrub(t, MAX_SHORT_CHARS) for t in _parse_list(rec.get("tags")) if isinstance(t, str)]
            conn.execute("INSERT INTO learnings (run_id, category, learning, tags) VALUES (?,?,?,?)",
                         (run_id, cat, text, json.dumps(tags)))
            n += 1
        except sqlite3.Error:
            continue
    return n


def _import_artifact(db_path: str, run_id: str, path: Path, artifact_type: str,
                     dest: str, as_json: bool) -> bool:
    from core.database import record_artifact

    raw = _read_bounded(path, 10**7)
    if raw is None:
        return False
    text = _scrub(raw.decode("utf-8", errors="replace"), 10**7)
    if as_json:
        try:
            text = json.dumps(json.loads(text), sort_keys=True)
        except ValueError:
            return False
    if not text.strip():
        return False
    # An import is text from a repository: the trust tier is what this
    # process knows about it, not what the file's own frontmatter claims.
    # Without the explicit tier, the OKF parser would take `verified: human`
    # from the document and index attacker-writable prose as human-reviewed
    # guidance for every later run.
    record_artifact(db_path, run_id, artifact_type, dest, text,
                    metadata={"imported": True, "trust_tier": "unverified"})
    return True


def _import_runs(db_path: str, runs_path: Path, *record_paths: Path) -> int:
    """Rebuilds the runs table (run id -> model) from the export: runs.jsonl
    when present, else whatever the records themselves say (a v2 export
    without the file, or one edited by hand). A v1 export says nothing and
    its runs stay of unknown model. Returns the number recorded."""
    from core.database import record_run

    pairs: Dict[str, str] = {}
    if runs_path.exists():
        for rec in _iter_jsonl(runs_path):
            run_id = _short(rec.get("run_id"))
            if run_id and _IDENT_RE.match(run_id):
                pairs.setdefault(run_id, _short(rec.get("model")))
    for path in record_paths:
        if not path.exists():
            continue
        if path.suffix == ".jsonl":
            for rec in _iter_jsonl(path):
                run_id, model = _short(rec.get("run_id")), _short(rec.get("model"))
                if run_id and model and _IDENT_RE.match(run_id):
                    pairs.setdefault(run_id, model)
        else:
            raw = _read_bounded(path)
            try:
                data = json.loads(raw.decode("utf-8", errors="replace")) if raw else {}
            except ValueError:
                data = {}
            if isinstance(data, dict):
                for entry in list(data.get("runs") or []) + list(data.get("scanned") or []):
                    if not isinstance(entry, dict):
                        continue
                    run_id = _short(entry.get("run_id") or entry.get("last_run_id"))
                    model = _short(entry.get("model"))
                    if run_id and model and _IDENT_RE.match(run_id):
                        pairs.setdefault(run_id, model)
    n = 0
    for run_id, model in pairs.items():
        if record_run(db_path, run_id, model, metadata={"imported": True}):
            n += 1
    return n


def _import_coverage(db_path: str, path: Path, repo_root: str, targets: List[str]) -> Tuple[int, int]:
    """Replays the coverage ledger under each target the next run may use, and
    stamps every scanned path as covered in the spend ledger (zero tokens, so
    it never counts as a cost observation). Returns (runs, paths)."""
    from core.cost import record_spend
    from core.memory import load_coverage, record_coverage

    raw = _read_bounded(path)
    if raw is None:
        return 0, 0
    try:
        data = json.loads(raw.decode("utf-8", errors="replace"))
    except ValueError:
        return 0, 0
    if not isinstance(data, dict):
        return 0, 0
    root = os.path.realpath(repo_root)
    # What each target's ledger already holds, so replaying the same export
    # twice (every per-file scan of a pull request imports it) adds nothing.
    present: Dict[str, set] = {}
    for target in targets:
        try:
            present[target] = {(str(r.get("run_id") or ""), tuple(sorted(r.get("examined") or [])))
                               for r in (load_coverage(db_path, target).get("runs") or [])
                               if isinstance(r, dict)}
        except Exception:
            present[target] = set()
    runs = 0
    for entry in (data.get("runs") or [])[:1000]:
        if not isinstance(entry, dict):
            continue
        examined = []
        for p in (entry.get("examined") or [])[:100_000]:
            rel = _clean_rel_path(p) if p != "." else "."
            if rel:
                examined.append(root if rel == "." else os.path.join(root, rel))
        if not examined:
            continue
        run_id = _short(entry.get("run_id")) or "imported"
        key = (run_id, tuple(sorted(set(examined))))
        for target in targets:
            if key in present[target]:
                continue
            record_coverage(db_path, run_id, target, examined, snapshot_id=_short(entry.get("snapshot_id")))
            present[target].add(key)
        runs += 1
    paths = 0
    # One row per (path, run): a path two models covered has two rows, each
    # under the run -- and so the model -- that covered it.
    already: set = set()
    try:
        conn = _connect(db_path)
        try:
            already = {(r[0], str(r[1] or "")) for r in conn.execute(
                "SELECT DISTINCT target, run_id FROM campaign_spend WHERE target IS NOT NULL").fetchall()}
        finally:
            conn.close()
    except sqlite3.Error:
        already = set()
    for entry in (data.get("scanned") or [])[:100_000]:
        if not isinstance(entry, dict):
            continue
        rel = _clean_rel_path(entry.get("path")) if entry.get("path") != "." else "."
        if not rel:
            continue
        abs_path = root if rel == "." else os.path.join(root, rel)
        run_id = _short(entry.get("last_run_id")) or "imported"
        if (abs_path, run_id) in already:
            paths += 1
            continue
        if record_spend(db_path, run_id, abs_path,
                        _short(entry.get("scan_mode")) or "whole", tokens=0,
                        metadata={"imported": True}):
            already.add((abs_path, run_id))
            paths += 1
    return runs, paths


def import_knowledge(db_path: str, in_dir: str, run_id: str, repo_root: str,
                     target: Optional[str] = None) -> Dict[str, Any]:
    """Reads a knowledge export into the database. Returns counts.

    Findings and learnings are added as history (the run ids they carry are
    kept); the threat model, architecture, and summary are recorded under
    `run_id` so the run's own tools find them; coverage is replayed for
    `repo_root` and, if different, `target`. Raises KnowledgeImportError when
    the directory is not an export this version reads; everything else
    degrades to "that part was not imported".
    """
    src = Path(in_dir)
    if not src.is_dir():
        raise KnowledgeImportError(f"{in_dir} is not a directory")
    raw = _read_bounded(src / MANIFEST, 1 << 20)
    if raw is None:
        raise KnowledgeImportError(f"{in_dir} has no readable {MANIFEST}")
    try:
        manifest = json.loads(raw.decode("utf-8", errors="replace"))
    except ValueError:
        raise KnowledgeImportError(f"{MANIFEST} is not JSON")
    version = manifest.get("schema_version") if isinstance(manifest, dict) else None
    if version not in READABLE_SCHEMA_VERSIONS:
        raise KnowledgeImportError(
            f"knowledge schema_version {version!r} is not one of {READABLE_SCHEMA_VERSIONS}; refusing to guess")

    from core.database import init_db

    init_db(db_path)
    counts: Dict[str, Any] = {}
    counts["runs"] = _import_runs(db_path, src / RUNS, src / FINDINGS, src / LEARNINGS, src / COVERAGE)
    conn = _connect(db_path)
    try:
        with conn:
            counts["findings"], counts["findings_skipped"] = _import_findings(conn, src / FINDINGS)
            counts["learnings"] = _import_learnings(conn, src / LEARNINGS)
    finally:
        conn.close()
    counts["threat_model"] = _import_artifact(db_path, run_id, src / THREAT_MODEL_JSON, *_ART_THREAT_MODEL, as_json=True)
    counts["threat_model_md"] = _import_artifact(db_path, run_id, src / THREAT_MODEL_MD, *_ART_THREAT_MODEL_MD, as_json=False)
    counts["architecture"] = _import_artifact(db_path, run_id, src / ARCHITECTURE_MD, *_ART_ARCHITECTURE, as_json=False)
    counts["summary"] = _import_artifact(db_path, run_id, src / SUMMARY_JSON, *_ART_SUMMARY, as_json=True)
    targets = [str(repo_root)]
    if target and os.path.realpath(str(target)) != os.path.realpath(str(repo_root)):
        targets.append(str(target))
    counts["coverage_runs"], counts["coverage_paths"] = _import_coverage(db_path, src / COVERAGE, str(repo_root), targets)
    return counts


def describe(counts: Dict[str, Any]) -> str:
    """One line for a log: what an import or export carried."""
    parts = [f"{counts.get('findings', 0)} finding(s)", f"{counts.get('learnings', 0)} learning(s)"]
    if counts.get("threat_model") or counts.get("threat_model_md"):
        parts.append("threat model")
    if counts.get("architecture"):
        parts.append("architecture")
    if counts.get("summary"):
        parts.append("summary")
    parts.append(f"coverage for {counts.get('coverage_paths', 0)} path(s)")
    return ", ".join(parts)


def export_to_context_tree(
    db_path: str,
    out_root: str | Path,
    task_description: str = "",
    repo_root: Optional[str] = None,
    task_id: str = "mantis_audit",
):
    """Materializes a Harness²-compatible ContextTree from a Mantis SQLite knowledge DB."""
    from core.harness_context import build_context_tree

    conn = _connect(db_path)
    try:
        findings = _export_findings(conn, repo_root)
        learnings = _export_learnings(conn)
    finally:
        conn.close()

    deliverables: Dict[str, List[Dict[str, Any]]] = {}
    for item in findings:
        raw_rid = str(item.get("run_id") or "default")
        rid = re.sub(r"[^A-Za-z0-9_.-]+", "_", raw_rid).strip("._") or "default"
        deliverables.setdefault(rid, []).append(item)

    decisions: List[str] = []
    for item in learnings:
        decisions.append(
            f"# [{item.get('category', 'learning')}] (run: {item.get('run_id', '')})\n\n"
            f"{item.get('learning', '')}\n"
        )

    return build_context_tree(
        out_root=out_root,
        task_id=task_id,
        task_description=task_description or "Mantis security audit rollout evidence.",
        deliverables=deliverables,
        decisions=decisions,
    )
